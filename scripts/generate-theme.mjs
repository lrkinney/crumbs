import { readFile, writeFile } from 'node:fs/promises';

const source = JSON.parse(await readFile(new URL('../design-system/tokens.resolved.json', import.meta.url), 'utf8'));
const tokens = Object.fromEntries(Object.entries(source).filter(([key]) => !key.startsWith('legacy.')).map(([key, token]) => {
  let value = token.value;
  if (token.type === 'color') value = `rgba(${[value.r, value.g, value.b].map(v => Math.round(v * 255)).join(', ')}, ${value.a})`;
  return [key, value];
}));
await writeFile(new URL('../src/theme/tokens.generated.ts', import.meta.url), `// Generated by npm run tokens. Edit design-system/tokens.resolved.json instead.\nexport const tokens = ${JSON.stringify(tokens, null, 2)} as const;\nexport type TokenPath = keyof typeof tokens;\nexport function token<K extends TokenPath>(path: K): (typeof tokens)[K] { return tokens[path]; }\n`);
const assets = JSON.parse(await readFile(new URL('../assets/crumbs/index.json', import.meta.url), 'utf8'));
const icons = {};
for (const asset of assets.filter(a => a.format === 'svg')) {
  let xml = await readFile(new URL(`../assets/crumbs/${asset.path.split('/').pop()}`, import.meta.url), 'utf8');
  if (asset.monochrome) xml = xml.replace(/(fill|stroke)="(?!none)[^"]+"/g, '$1="currentColor"');
  icons[asset.id] = `data:image/svg+xml;base64,${Buffer.from(xml.replace(/currentColor/g, '#000000')).toString('base64')}`;
}
await writeFile(new URL('../src/theme/icons.generated.ts', import.meta.url), `// Generated from original Figma SVG exports.\nexport const icons = ${JSON.stringify(icons)} as const;\n`);
console.log(`Generated ${Object.keys(tokens).length} native tokens and ${Object.keys(icons).length} icons.`);
